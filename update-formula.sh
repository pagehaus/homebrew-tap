#!/usr/bin/env bash
# Writes Formula/pagehaus.rb for a pagehaus release: ./update-formula.sh [version], the latest release if left out.
# Uses the release's SHA256SUMS, so the formula pins exactly the files that were published.
set -euo pipefail
cd "$(dirname "$0")"

version="${1:-$(gh release view --repo pagehaus/cli --json tagName --jq .tagName)}"
version="${version#v}"
sums=$(curl -fsSL "https://github.com/pagehaus/cli/releases/download/v$version/SHA256SUMS")
sha() { awk -v f="pagehaus-$1.tar.gz" '$2 == f { print $1 }' <<<"$sums"; }
for rid in osx-arm64 osx-x64 linux-arm64 linux-x64; do
  [ -n "$(sha "$rid")" ] || { echo "No checksum for $rid in v$version's SHA256SUMS" >&2; exit 1; }
done

url="https://github.com/pagehaus/cli/releases/download/v$version"
cat > Formula/pagehaus.rb <<RUBY
# Generated by update-formula.sh from the v$version release of github.com/pagehaus/cli: don't edit by hand.
class Pagehaus < Formula
  desc "Preview, check and deploy plain HTML sites, with Server Side Includes"
  homepage "https://pagehaus.app/cli"
  license "MIT"

  on_macos do
    on_arm do
      url "$url/pagehaus-osx-arm64.tar.gz"
      sha256 "$(sha osx-arm64)"
    end
    on_intel do
      url "$url/pagehaus-osx-x64.tar.gz"
      sha256 "$(sha osx-x64)"
    end
  end

  on_linux do
    on_arm do
      url "$url/pagehaus-linux-arm64.tar.gz"
      sha256 "$(sha linux-arm64)"
    end
    on_intel do
      url "$url/pagehaus-linux-x64.tar.gz"
      sha256 "$(sha linux-x64)"
    end
  end

  def install
    bin.install "pagehaus"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/pagehaus --version")
    (testpath/"site/includes").mkpath
    (testpath/"site/includes/name.html").write "Pagehaus"
    (testpath/"site/index.html").write <<~HTML
      <!doctype html><html><head><title>Test</title><meta name="description" content="A test"></head>
      <body><h1><!--#include virtual="/includes/name.html" --></h1></body></html>
    HTML
    assert_match "No problems found", shell_output("#{bin}/pagehaus check #{testpath}/site")
  end
end
RUBY
echo "Formula/pagehaus.rb: $version"
